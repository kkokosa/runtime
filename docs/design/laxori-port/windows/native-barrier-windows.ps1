# Builds and runs the native test of the Laxori write barrier assembly with MSVC and ml64 (the Windows twin of
# BarrierTest/native-barrier-linux.sh), then builds it again with the vector-save control and requires that a vector check fails.
# usage: native-barrier-windows.ps1 [-Output <dir>] [-Repo <path>]
param(
    [string]$Output = 'C:\lx-barrier',
    [string]$Repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path
)
$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Force $Output | Out-Null
$Output = (Resolve-Path $Output).Path
$gc = Join-Path $Repo 'src\coreclr\gc_laxori'
$vm = Join-Path $Repo 'src\coreclr\vm\amd64'
$test = Join-Path $Repo 'docs\design\laxori-port\BarrierTest'
$vsenv = "call `"$Repo\eng\native\init-vs-env.cmd`" x64 >nul"

# AsmConstants.inc is generated by the runtime build; the barrier uses nothing from it, but AsmMacros.inc names two constants.
$inc = Join-Path $Output 'inc'
New-Item -ItemType Directory -Force $inc | Out-Null
Set-Content -Path (Join-Path $inc 'AsmConstants.inc') -Value "OFFSETOF__RuntimeThreadLocals__ee_alloc_context EQU 0`nOFFSET__TEB__ThreadLocalStoragePointer EQU 58h"

function Build([string]$name, [string]$asmDef) {
    $obj = Join-Path $Output "$name.asm.obj"
    $tobj = Join-Path $Output "$name.test.asm.obj"
    $exe = Join-Path $Output "$name.exe"
    $log = Join-Path $Output "$name.build.log"
    Remove-Item $exe -ErrorAction SilentlyContinue
    $cmd = "$vsenv && cd /d `"$Output`" && ml64.exe /nologo /c $asmDef /I`"$inc`" /I`"$vm`" /Fo`"$obj`" `"$gc\amd64\laxori_writebarrier.asm`" && ml64.exe /nologo /c /Fo`"$tobj`" `"$test\laxori-barrier-test-win.asm`" && cl.exe /nologo /std:c++17 /EHsc /W4 /WX /wd4100 /wd4324 /O2 /MT /I`"$gc`" `"$test\laxori-barrier-test.cpp`" `"$gc\laxori_write_barrier.cpp`" `"$obj`" `"$tobj`" /Fe:`"$exe`" /Fo:`"$Output\\`""
    & $env:ComSpec /d /s /c $cmd *> $log
    return (Test-Path $exe)
}

$failed = 0
if (-not (Build 'normal' '')) { Get-Content (Join-Path $Output 'normal.build.log') | Select-Object -Last 20; exit 1 }
& (Join-Path $Output 'normal.exe') *> (Join-Path $Output 'normal.log')
if ($LASTEXITCODE -ne 0) { $failed = 1 }
Get-Content (Join-Path $Output 'normal.log') | ForEach-Object { $_ }

if (-not (Build 'no-vector-save' '/DLAXORI_WB_CONTROL_NO_VECTOR_SAVE')) { Write-Output 'control no-vector-save: build failed'; $failed = 1 }
else {
    & (Join-Path $Output 'no-vector-save.exe') *> (Join-Path $Output 'no-vector-save.log')
    $code = $LASTEXITCODE
    $vec = Select-String -Path (Join-Path $Output 'no-vector-save.log') -Pattern '^FAIL: vector' -Quiet
    if ($code -eq 1 -and $vec) { Write-Output "control no-vector-save: a vector check fails as required" }
    else { Write-Output "control no-vector-save: NO vector check failed (exit $code)"; $failed = 1 }
}
Write-Output "barrier native test failed=$failed"
exit $failed
